use diagnostics_api::data_item::{ReadRequest, WriteRequest};
use sdvgenerated::data_item_interface::DataItem;
use sdvgenerated::diagnostics_manager_service::DiagnosticsManagerService;
use sdvgenerated_rpc_data_item::client::DataItemClient;
use sdvmiddleware_rpc_grpc::grpc_client_transport::GrpcClientTransport;
use std::collections::HashMap;

// Current workaround to talk to a specific server implementation.
// Future Middleware API to achieve this might look completely different.
fn create_data_item_client(target_server_service_bundle: String) -> DataItemClient {
    DataItemClient::new(Box::new(GrpcClientTransport::new(&target_server_service_bundle)))
}

fn read_data_item_request(data_item_id: &str) -> ReadRequest {
    ReadRequest { id: data_item_id.to_string(), ..Default::default() }
}

fn write_data_item_request(data_item_id: &str, value: Vec<u8>) -> WriteRequest {
    WriteRequest { id: data_item_id.to_string(), value, ..Default::default() }
}

fn main() {
    let first_data_item = "data_item_id1";
    let second_data_item = "data_item_id2";

    let mut data_item_providers = HashMap::new();
    data_item_providers.insert(first_data_item, "DiagnosticsProviderService1");
    data_item_providers.insert(second_data_item, "DiagnosticsProviderService2");

    // Create service instance to register topics, etc.
    let _service = DiagnosticsManagerService::new();
    println!("Diagnostics Manager service bundle started.");

    // Currently, `service.data_item_client` generated by VSIDL is communicating with
    // "DiagnosticsProviderService1", but that might change, e.g. if order of service
    // bundles definitions changes
    //
    // // Might point to different server, if VSIDL code is regenerated
    // let response = service.data_item_client.read(read_data_item_request(first_data_item));
    //
    // Thus, for now, prefer to manually create client, if:
    // - you expected multiple servers to exist, AND
    // - you do care which server to talk to

    let first_data_item_client =
        create_data_item_client(data_item_providers[first_data_item].to_string());

    let response = first_data_item_client.read(read_data_item_request(first_data_item));
    println!("Fetch {:?}: {:?}.", first_data_item, response);

    let new_value = vec![2];
    let response =
        first_data_item_client.write(write_data_item_request(first_data_item, new_value.clone()));
    println!(
        "Update {:?} to a new value {:?}. Response: {:?}.",
        first_data_item, new_value, response
    );

    let response = first_data_item_client.read(read_data_item_request(first_data_item));
    println!("Fetch {:?} data item after update: {:?}.", first_data_item, response);

    let second_data_item_client =
        create_data_item_client(data_item_providers[second_data_item].to_string());

    let response = second_data_item_client.read(read_data_item_request(first_data_item));
    println!(
        "Trying to fetch {:?} from the second provider, fails with response: {:?}.",
        first_data_item, response
    );

    let response = second_data_item_client.read(read_data_item_request(second_data_item));
    println!("Fetch {:?} from the second provider: {:?}.", second_data_item, response);
}
